-- ── Interview Questions ───────────────────────────────────────
CREATE TABLE IF NOT EXISTS interview_questions_ai_interview (
  id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  session_id           UUID REFERENCES interview_sessions_ai_interview(id) ON DELETE CASCADE,
  question_text        TEXT NOT NULL,
  question_type        TEXT DEFAULT 'technical'
                         CHECK (question_type IN ('technical','behavioral','situational','cultural')),
  source               TEXT DEFAULT 'ai_generated',
  order_index          INT NOT NULL,
  parent_question_id   UUID REFERENCES interview_questions_ai_interview(id),
  plan_item_id         TEXT,
  competency_ids       JSONB NOT NULL DEFAULT '[]'::jsonb,
  decision_rationale   TEXT,
  -- Why a follow-up question was inserted (NULL for primary questions).
  insufficiency_reason TEXT CHECK (insufficiency_reason IN ('lacks_depth','lacks_evidence','vague','irrelevant')),
  created_at           TIMESTAMPTZ DEFAULT now()
);

COMMENT ON COLUMN interview_questions_ai_interview.insufficiency_reason IS
  'For follow-up questions: the failure mode detected in the parent answer that triggered this follow-up. NULL for primary questions.';

