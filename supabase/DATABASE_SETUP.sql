-- Returns true if the calling JWT belongs to an HR role.
-- Used by DELETE policies so we don't repeat the COALESCE everywhere.
CREATE OR REPLACE FUNCTION public.is_hr()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT COALESCE(
    auth.jwt() -> 'app_metadata' ->> 'role',
    auth.jwt() -> 'user_metadata' ->> 'role',
    ''
  ) IN ('hr_admin', 'hr_recruiter', 'system');
$$;

-- Trigger function that keeps updated_at fresh on every row update.
CREATE OR REPLACE FUNCTION trigger_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

